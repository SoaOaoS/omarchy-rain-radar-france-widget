#!/usr/bin/env node
// Builds Towns.js, the French communes the panel's town search looks in, from
// the State's commune directory (API Découpage administratif, geo.api.gouv.fr;
// Licence Ouverte 2.0, see MAP-SOURCES.md). One request:
//
//   curl -fsSL -o communes.json \
//     "https://geo.api.gouv.fr/communes?fields=nom,code,centre,population,codeDepartement&format=json"
//   node tools/build-towns.cjs communes.json > Towns.js
//
// Every commune of mainland France and Corsica (those inside the map), most
// populous first, each with its department number: many names repeat (there
// are a dozen Saint-Aubin), so the search shows "Saint-Aubin (39)".
const fs = require("node:fs")
const path = require("node:path")
const MapModel = require(path.join(__dirname, "..", "MapModel.js"))

const file = process.argv[2]
if (!file) { console.error("usage: node tools/build-towns.cjs communes.json > Towns.js"); process.exit(2) }

const places = []
for (const c of JSON.parse(fs.readFileSync(file, "utf8"))) {
  const at = c.centre && c.centre.coordinates
  if (!c.nom || !at || !c.codeDepartement) continue
  const [lon, lat] = at
  if (!MapModel.contains(lat, lon)) continue // overseas departments and territories
  places.push({ name: c.nom, lat, lon, pop: Number.isFinite(c.population) ? c.population : 0, dept: c.codeDepartement })
}
places.sort((a, b) => b.pop - a.pop || a.name.localeCompare(b.name, "fr") || a.dept.localeCompare(b.dept))

const round3 = (v) => Math.round(v * 1e3) / 1e3
const rows = places.map((p) => JSON.stringify([p.name, round3(p.lat), round3(p.lon), p.pop, p.dept]))
process.stdout.write(
  "// Generated by tools/build-towns.cjs from geo.api.gouv.fr; do not edit.\n" +
  "// Source: API Découpage administratif (INSEE, IGN), Licence Ouverte 2.0 (see MAP-SOURCES.md).\n" +
  "// The communes of mainland France and Corsica for the town search, most populous first:\n" +
  "// [name, latitude, longitude, population, department]\n" +
  "var towns = [\n" + rows.join(",\n") + "\n]\n\n" +
  'if (typeof module !== "undefined") module.exports = { towns: towns }\n')
